const dictionaries: Record<Lang, Record<Key, string>> = { en, vi };

export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

function interpolate(template: string, vars?: Record<string, string | number>) {
  return vars ? template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match)) : template;
}

export function makeTranslator(lang: Lang) {
  const dictionary = dictionaries[lang];
  const t: Translate = (key, vars) => interpolate(dictionary[key], vars);
  const tx = (key: string, fallback: string, vars?: Record<string, string | number>) =>
    interpolate(key in dictionary ? dictionary[key as Key] : fallback, vars);
  return { t, tx };
}

export function loadLang(): Lang {
  const saved = typeof localStorage === 'undefined' ? null : localStorage.getItem(STORAGE_KEY);
  return saved === 'en' || saved === 'vi' ? saved : DEFAULT_LANG;
}

export function saveLang(lang: Lang) {
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.lang = lang;
}

export function localeOf(lang: Lang) {
  return lang === 'vi' ? 'vi-VN' : 'en-US';
}

