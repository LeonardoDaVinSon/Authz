const VI_DETAIL_PATTERNS: [RegExp, string][] = [
  [/^"(.*)" is not allowed$/, '"$1" không được phép'],
  [/^expires in (\d+)s$/, 'hết hạn sau $1 giây'],
  [/^expires (\d+)s ago$/, 'đã hết hạn $1 giây trước'],
  [/^valid from in (\d+)s$/, 'có hiệu lực sau $1 giây'],
  [/^valid from (\d+)s ago$/, 'có hiệu lực từ $1 giây trước'],
];

export function translateTraceDetail(detail: string, lang: Lang) {
  if (lang === 'en') return detail;
  if (detail in VI_DETAILS) return VI_DETAILS[detail];
  for (const [pattern, replacement] of VI_DETAIL_PATTERNS) {
    if (pattern.test(detail)) return detail.replace(pattern, replacement);
  }
  return detail;
}
